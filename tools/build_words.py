#!/usr/bin/env python3
"""Validate words_list.py and emit words.json.

    python3 tools/build_words.py

The validation is the point. The cloze drill is generated at runtime by blanking the headword
out of a sense's example, so an example that does not contain its own headword would produce a
question with nothing missing. That is caught here rather than discovered by a learner.

Output is one sense per line, like verbs.json, so a content change shows up in the diff exactly
where it happened.
"""

import json
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from words_list import WORDS  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "words.json")


def fold(s):
    """Lowercase and strip accents, so `Fíjate` matches headword `fíjate`."""
    return "".join(c for c in unicodedata.normalize("NFD", s.lower())
                   if unicodedata.category(c) != "Mn")


def contains_headword(example, headword):
    """Does `example` contain `headword` as whole word(s)?

    Accent- and case-insensitive. Multi-word headwords (`o sea`, `de todas formas`) are matched
    as a phrase. A headword may appear inflected in ways we do not try to guess -- if this is
    too strict for some entry, fix the example rather than loosening the check.
    """
    hay, needle = fold(example), fold(headword)
    return re.search(r"(?<![a-z])" + re.escape(needle) + r"(?![a-z])", hay) is not None


def validate(words):
    errors = []
    seen = {}

    for i, w in enumerate(words):
        where = "entry %d (%r)" % (i, w.get("w", "?"))

        for field in ("w", "pos", "grp", "tier", "senses"):
            if not w.get(field):
                errors.append("%s: missing %s" % (where, field))
        if errors and not w.get("w"):
            continue

        head = w["w"]
        if fold(head) in seen:
            errors.append("%s: duplicate of entry %d" % (where, seen[fold(head)]))
        seen[fold(head)] = i

        if w.get("tier") not in (1, 2):
            errors.append("%s: tier must be 1 or 2, got %r" % (where, w.get("tier")))

        if not isinstance(w.get("senses"), list) or not w["senses"]:
            errors.append("%s: needs at least one sense" % where)
            continue

        for j, s in enumerate(w["senses"]):
            at = "%s sense %d" % (where, j)
            for field in ("g", "ex", "en"):
                if not s.get(field, "").strip():
                    errors.append("%s: missing %s" % (at, field))
            if not s.get("ex"):
                continue
            # The one that matters: cloze is generated by blanking this form out of the example.
            target = s.get("blank") or head
            if not contains_headword(s["ex"], target):
                hint = (" (set blank= to the inflected form actually used)"
                        if not s.get("blank") else "")
                errors.append("%s: example %r does not contain %r, so no cloze can be "
                              "generated from it%s" % (at, s["ex"], target, hint))

    return errors


def render(words):
    """One sense per line; stable key order; readable diffs."""
    out = []
    for w in words:
        lines = []
        lines.append('  "w": %s,' % json.dumps(w["w"], ensure_ascii=False))
        lines.append('  "pos": %s,' % json.dumps(w["pos"], ensure_ascii=False))
        lines.append('  "grp": %s,' % json.dumps(w["grp"], ensure_ascii=False))
        lines.append('  "tier": %d,' % w["tier"])
        senses = []
        for s in w["senses"]:
            d = {"g": s["g"], "ex": s["ex"], "en": s["en"]}
            if s.get("blank"):
                d["blank"] = s["blank"]
            senses.append(json.dumps(d, ensure_ascii=False, sort_keys=False))
        lines.append('  "senses": [\n    ' + ",\n    ".join(senses) + "\n  ]"
                     + ("," if w.get("note") else ""))
        if w.get("note"):
            lines.append('  "note": %s' % json.dumps(w["note"], ensure_ascii=False))
        out.append(" {\n" + "\n".join(lines) + "\n }")
    return "[\n" + ",\n".join(out) + "\n]\n"


def main():
    errors = validate(WORDS)
    if errors:
        print("words_list.py has %d problem(s):" % len(errors), file=sys.stderr)
        for e in errors:
            print("  - " + e, file=sys.stderr)
        return 1

    text = render(WORDS)

    # The emitted file must parse back to exactly the data we meant to write.
    reparsed = json.loads(text)
    expected = [{k: v for k, v in
                 [("w", w["w"]), ("pos", w["pos"]), ("grp", w["grp"]), ("tier", w["tier"]),
                  ("senses", [{k: v for k, v in
                               [("g", s["g"]), ("ex", s["ex"]), ("en", s["en"])]
                               + ([("blank", s["blank"])] if s.get("blank") else [])}
                              for s in w["senses"]])]
                 + ([("note", w["note"])] if w.get("note") else [])}
                for w in WORDS]
    assert reparsed == expected, "rendered JSON does not round-trip"

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)

    senses = sum(len(w["senses"]) for w in WORDS)
    tier1 = sum(1 for w in WORDS if w["tier"] == 1)
    groups = len({w["grp"] for w in WORDS})
    notes = sum(1 for w in WORDS if w.get("note"))
    print("words.json: %d words, %d senses, %d groups, %d notes" % (len(WORDS), senses, groups, notes))
    print("  tier 1: %d   tier 2: %d" % (tier1, len(WORDS) - tier1))
    blanks = sum(1 for w in WORDS for s in w["senses"] if s.get("blank"))
    print("  every example contains its blank target, so %d cloze items are generatable "
          "(%d via an explicit blank=)" % (senses, blanks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
